// NormalizedEvidenceRef references a normalized evidence item and carries its normalized fact
// (controlled JSON capped by normalizeFact, all marked as estimate; never carries
// raw payloads or plaintext SQL — C2 fix: the model must see fact content to make judgments).
type RunState string

const (
	RunStateQueued   RunState = "queued"
	RunStateRunning  RunState = "running"
	RunStateReady    RunState = "ready"
	RunStateBlocked  RunState = "blocked"
	RunStatePartial  RunState = "partial"
	RunStateFailed   RunState = "failed"
	RunStateOutdated RunState = "outdated"
)

// ToolDescriptor is a tool declaration visible to the model (built-in fact tools only;
// Prompt Tools and internal knowledge use deterministic injection and do not enter free scheduling).
// InputSchema is a JSON-Schema-shaped parameter declaration (NEW-AI-03 bootstrap: the model must
// know parameter names/types/requiredness to construct valid tool calls; generated by registry
// Descriptor.InputSchema, containing only parameter names and types without any identifiers).
func ValidRunState(s RunState) bool {
	switch s {
	case RunStateQueued, RunStateRunning, RunStateReady,
		RunStateBlocked, RunStatePartial, RunStateFailed, RunStateOutdated:
		return true
	}
	return false
}

// Response is provider_port.response (api/contracts/ai-review-output.schema.json).
func RunTerminal(s RunState) bool {
	switch s {
	case RunStateReady, RunStateBlocked, RunStatePartial, RunStateFailed, RunStateOutdated:
		return true
	}
	return false
}

// Finding is a Finding entry in the output Schema.
type RunTrigger string

const (
	// ToolRequest is a follow-up tool call requested by the model (validated against the runtime allowlist).
	RunEventStarted RunTrigger = "started"
	// Contract limits (provider_port).
	RunEventCompleted RunTrigger = "completed"
	// ErrSchemaInvalid 2009: output schema is invalid (still invalid after the repair request).
	RunEventRiskBlocked RunTrigger = "risk_blocked"
	// ErrRejected deterministic rejection (authentication failure / invalid input), not retried.
	RunEventIncomplete RunTrigger = "incomplete"
	// ErrNoProvider all candidates are unavailable or do not satisfy the contract (fail closed).
	RunEventFailed RunTrigger = "failed"
	// Endpoint is a decryption-ready Provider endpoint (secrets reside in memory only during the call).
	RunEventInputsChanged RunTrigger = "inputs_changed"
)

var runEdges = map[RunState]map[RunTrigger]RunState{
	RunStateQueued: {
		RunEventStarted:       RunStateRunning,
		RunEventFailed:        RunStateFailed,
		RunEventInputsChanged: RunStateOutdated,
	},
	RunStateRunning: {
		RunEventCompleted:     RunStateReady,
		RunEventRiskBlocked:   RunStateBlocked,
		RunEventIncomplete:    RunStatePartial,
		RunEventFailed:        RunStateFailed,
		RunEventInputsChanged: RunStateOutdated,
	},
	// PlanHash folds the effective Provider chain (order + model + both hashes + canonicalized generation parameters)
	// into a Run-scoped plan hash. Any change to the chain invalidates unsubmitted Reviews.
	// S008: the three generation parameters participate in plan identity in canonical form — fixed key order,
	// omitted means absent, equivalent empty override (no user keys) produces the same identity as omission,
	// unique decimal representation for float64 (1e0 and 1 share identity), independent of map iteration order;
	// system-managed keys (structured_output_mode) do not enter plan identity.
	RunStateReady: {
		RunEventInputsChanged: RunStateOutdated,
	},
	RunStateBlocked: {
		RunEventInputsChanged: RunStateOutdated,
	},
	RunStatePartial: {
		RunEventInputsChanged: RunStateOutdated,
	},
	RunStateFailed: {
		RunEventInputsChanged: RunStateOutdated,
	},
}

// GenerationParamsCanonical folds the three generation parameters in configuration into a
// canonical string (fixed key order max_tokens -> reasoning_effort -> temperature;
// keys with invalid values or missing keys do not participate). Empty result = no user override, sharing identity with full omission.
func RunTransition(s RunState, trigger RunTrigger) (RunState, error) {
	if s == RunStateOutdated {
		return s, ErrTerminalState
	}
	edges, ok := runEdges[s]
	if !ok {
		return s, ErrIllegalTransition
	}
	next, ok := edges[trigger]
	if !ok {
		if RunTerminal(s) {
			return s, ErrTerminalState
		}
		return s, ErrIllegalTransition
	}
	return next, nil
}

// Validate checks that Endpoint satisfies chain admission (non-empty 64-character hex hashes).
func RunOutcomeFailedStates() []RunState {
	return []RunState{RunStateFailed, RunStatePartial, RunStateBlocked}
}

// CallOutcome is the artifact of a single structured call: response + actual Token usage
// (budget ledger input, budget_and_capacity.actual_usage).
// S008: Calls records each real HTTP boundary individually (one row each for initial / backoff retry /
// schema repair; failure paths also preserve reported usage — Usage-02 never treats failed calls as free),
// serving as input to the reference pricing ledger.
type StageReviewState string

const (
	StageStatePending StageReviewState = "pending"
	StageStateRunning StageReviewState = "running"
	StageStatePassed  StageReviewState = "passed"
	StageStateBlocked StageReviewState = "blocked"
	StageStatePartial StageReviewState = "partial"
	StageStateFailed  StageReviewState = "failed"
)

// UsageDetail is tri-state usage detail: nil = unknown (missing field / null / type error / negative),
// non-nil pointer = explicit upstream count (0 is a valid zero, not unknown). Relational validity
// (e.g. cached + cache_write <= input) is evaluated by the reference pricing layer; the adapter reports verbatim.
func ValidStageReviewState(s StageReviewState) bool {
	switch s {
	case StageStatePending, StageStateRunning, StageStatePassed,
		StageStateBlocked, StageStatePartial, StageStateFailed:
		return true
	}
	return false
}

// CallRecord is the accounting fact for a single real HTTP call (PRD section 5 per-call record).
// HTTPStatus=0 indicates no response was received (network error / timeout / cancellation); Detail=nil
// indicates upstream did not report usage (unknown, never converted to 0). The three generation parameter
// snapshots are taken from the Endpoint configuration for that call (configured value; zero value = omitted / not sent).
func StageTerminal(s StageReviewState) bool {
	switch s {
	case StageStatePassed, StageStateBlocked, StageStatePartial, StageStateFailed:
		return true
	}
	return false
}

// Generation parameter snapshot (S008 section 5: configured/omitted recorded separately from usage).
type Severity string

const (
	SeverityNone Severity = "none"
	// Call outcome constants (CallRecord.Outcome).
	SeverityInfo     Severity = "info"
	SeverityLow      Severity = "low"
	SeverityMedium   Severity = "medium"
	SeverityHigh     Severity = "high"
	SeverityCritical Severity = "critical"
)

// Client is the Provider Port (provider_port.methods).
func SeverityRank(s Severity) int {
	switch s {
	case SeverityNone, SeverityInfo:
		return 0
	case SeverityLow:
		return 1
	case SeverityMedium:
		return 2
	case SeverityHigh:
		return 3
	case SeverityCritical:
		return 4
	}
	return -1
}

// ValidateConfiguration validates configuration usability (without sending review payloads).
func MaxSeverity(a, b Severity) Severity {
	if SeverityRank(a) >= SeverityRank(b) {
		return a
	}
	return b
}

