// ---- Minimal fake driver (covers only the surface reached by Execute -> runAttempt -> claimAttempt) ----

// contestFx metadata DB fake driver: implements both driver.Connector and driver.Conn.
type contestFx struct {
	attemptCols []string // Column names returned by First query
	attemptRow  []driver.Value
	claimAffect int64 // RowsAffected for claim CAS update (0 = lease contention)
	failSelect  error // When non-nil, reading execution_attempts fails directly with this error
}

func (f *contestFx) Connect(context.Context) (driver.Conn, error) { return f, nil }
func (f *contestFx) Driver() driver.Driver                        { return contestDriver{} }

type contestDriver struct{}

func (contestDriver) Open(string) (driver.Conn, error) {
	return nil, errors.New("contest fake: dsn open unsupported")
}

func (f *contestFx) Prepare(string) (driver.Stmt, error) {
	return nil, errors.New("contest fake: prepare unsupported")
}
func (f *contestFx) Close() error { return nil }
func (f *contestFx) Begin() (driver.Tx, error) {
	return nil, errors.New("contest fake: tx unsupported")
}

func (f *contestFx) QueryContext(_ context.Context, query string, _ []driver.NamedValue) (driver.Rows, error) {
	// Table names generated by GORM are quoted (FROM "execution_attempts"), so match uniformly
	// via lowercase substring; Exec/Query separation guarantees only SELECT reaches here.
	lq := strings.ToLower(query)
	switch {
	case strings.Contains(lq, "execution_attempts"):
		if f.failSelect != nil {
			return nil, f.failSelect
		}
		return &contestRows{cols: f.attemptCols, row: f.attemptRow}, nil
	default:
		return nil, errors.New("contest fake: unexpected query: " + firstLine(query))
	}
}

func (f *contestFx) ExecContext(_ context.Context, query string, _ []driver.NamedValue) (driver.Result, error) {
	lq := strings.ToLower(query)
	switch {
	case strings.Contains(lq, "update execution_attempts set fence_token"):
		// claimAttempt uses handwritten raw SQL (unquoted lowercase).
		return contestResult{rows: f.claimAffect}, nil
	case strings.Contains(lq, "insert into") && strings.Contains(lq, "audit_events"):
		return contestResult{rows: 1}, nil
	default:
		return nil, errors.New("contest fake: unexpected exec: " + firstLine(query))
	}
}

func firstLine(q string) string {
	if i := strings.IndexByte(q, '\n'); i >= 0 {
		return q[:i]
	}
	return q
}

type contestResult struct{ rows int64 }

func (r contestResult) LastInsertId() (int64, error) { return 0, errors.New("unimplemented") }
func (r contestResult) RowsAffected() (int64, error) { return r.rows, nil }

type contestRows struct {
	cols []string
	row  []driver.Value
	done bool
}

func (r *contestRows) Columns() []string { return r.cols }
func (r *contestRows) Close() error      { return nil }
func (r *contestRows) Next(dest []driver.Value) error {
	if r.done {
		return io.EOF
	}
	r.done = true
	if len(r.row) != len(dest) {
		return errors.New("contest fake: row width mismatch")
	}
	copy(dest, r.row)
	return nil
}

// newContestRunner constructs a Runner on the fake metadata DB. The path does not touch Crypter;
// audit writes in the binding-mismatch scenario go through Recorder into the fake driver's audit_events insert;
// instance is a package-private field (configurable by same-package tests).
func newContestRunner(t *testing.T, fx *contestFx) (*Runner, *gorm.DB) {
	t.Helper()
	sqlDB := sql.OpenDB(fx)
	t.Cleanup(func() { _ = sqlDB.Close() })
	db, err := gorm.Open(gormpostgres.New(gormpostgres.Config{
		Conn: sqlDB, WithoutReturning: true,
	}), &gorm.Config{Logger: gormlogger.Discard, SkipDefaultTransaction: true})
	if err != nil {
		t.Fatalf("gorm open: %v", err)
	}
	recorder, err := auditlog.NewRecorder(db)
	if err != nil {
		t.Fatalf("recorder: %v", err)
	}
	return NewRunner(&Services{DB: db, Recorder: recorder, instance: "contest-worker"}), db
}

// seedContestAttempt configures the execution_attempts row returned by First.
func seedContestAttempt(fx *contestFx, orderID, stageID, boundary string, fence int64) {
	fx.attemptCols = []string{
		"id", "order_id", "stage_id", "initiated_by_user_id_snapshot",
		"initiated_by_username_snapshot", "execution_kind", "state",
		"send_boundary", "fence_token", "version", "created_at",
	}
	fx.attemptRow = []driver.Value{
		"attempt-1", orderID, stageID, "u1", "exec1", "dml", "running",
		boundary, fence, int64(1), time.Now().UTC(),
	}
}

// TestExecuteTranslatesClaimContestToCrashSemantics Claim contention (claim CAS
// 0 rows = Attempt lease is still held by an active worker or adjudicated dead by reconciliation)
// -> Execute must wrap and return with crash semantics. Task-layer verification point: worker.RunOnce
// checks errors.Is(err, ErrWorkerCrashed) (worker.go:93) before FailBusiness (worker.go:106) ->
// hitting the crash branch avoids persisting a terminal task state so it converges via reclaim after
// lease expiry; this unit test asserts the exact input to that check.
// End-to-end coverage under real PostgreSQL: TestLiveAttemptLeaseNotStealable in
// reclaim_integration_test.go (executed in CI integration builds).
func TestExecuteTranslatesClaimContestToCrashSemantics(t *testing.T) {
	cases := []struct {
		name     string
		boundary string
	}{
		// Task reclaims an active lease that has already crossed the send boundary: claim precedes result_unknown adjudication.
		{"live lease beyond send boundary", "sent"},
		// Active lease at zero-send boundary: claim contention on the normal claim path.
		{"live lease before send boundary", "not_started"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			fx := &contestFx{claimAffect: 0}
			seedContestAttempt(fx, "order-1", "stage-1", tc.boundary, 2)
			runner, db := newContestRunner(t, fx)
			raw, err := json.Marshal(TaskInput{
				AttemptID: "attempt-1", OrderID: "order-1", StageID: "stage-1",
			})
			if err != nil {
				t.Fatal(err)
			}
			execErr := runner.Execute(context.Background(), db, raw, nil, nil)
			if execErr == nil {
				t.Fatal("claim contest must surface an error, got nil")
			}
			// Core assertion: the error chain matches tasks.ErrWorkerCrashed — causing the worker
			// to take the crash branch (skipping FailBusiness and converging via reclaim after lease expiry).
			if !errors.Is(execErr, tasks.ErrWorkerCrashed) {
				t.Fatalf("Execute must translate claim contest into ErrWorkerCrashed, got %v", execErr)
			}
			// The original contention error remains observable in the message (%v does not enter the chain, preserved in text only).
			var de *domain.Error
			if errors.As(execErr, &de) {
				t.Fatalf("wrapped error must not leak *domain.Error into chain (worker crash semantics only), got %v", de)
			}
			if !strings.Contains(execErr.Error(), domain.ErrConcurrent().Error()) {
				t.Fatalf("error message should retain original contest error text, got %q", execErr.Error())
			}
		})
	}
}

// TestExecuteDoesNotWrapNonContestErrors Negative control: non-1004 domain errors and non-domain
// errors must never be translated into crash semantics (otherwise the task could never FailBusiness
// and would have to wait for lease expiry — dragging deterministic failures into delayed convergence).
func TestExecuteDoesNotWrapNonContestErrors(t *testing.T) {
	t.Run("non-concurrent domain error passes through", func(t *testing.T) {
		// Payload binding mismatch (SEC-0060): runAttempt returns ErrIllegal(1010).
		fx := &contestFx{claimAffect: 1}
		seedContestAttempt(fx, "order-other", "stage-1", "not_started", 1)
		runner, db := newContestRunner(t, fx)
		raw, err := json.Marshal(TaskInput{
			AttemptID: "attempt-1", OrderID: "order-1", StageID: "stage-1",
		})
		if err != nil {
			t.Fatal(err)
		}
		execErr := runner.Execute(context.Background(), db, raw, nil, nil)
		if execErr == nil {
			t.Fatal("binding mismatch must fail closed")
		}
		var de *domain.Error
		if !errors.As(execErr, &de) || de.Code != domain.CodeIllegalTransition {
			t.Fatalf("binding mismatch must surface domain error 1010, got %v", execErr)
		}
		if errors.Is(execErr, tasks.ErrWorkerCrashed) {
			t.Fatalf("non-concurrent domain error must not be wrapped as crash: %v", execErr)
		}
	})
	t.Run("raw database error passes through", func(t *testing.T) {
		boom := errors.New("contest fake: metadata db unavailable")
		fx := &contestFx{failSelect: boom}
		seedContestAttempt(fx, "order-1", "stage-1", "not_started", 1)
		runner, db := newContestRunner(t, fx)
		raw, err := json.Marshal(TaskInput{
			AttemptID: "attempt-1", OrderID: "order-1", StageID: "stage-1",
		})
		if err != nil {
			t.Fatal(err)
		}
		execErr := runner.Execute(context.Background(), db, raw, nil, nil)
		if !errors.Is(execErr, boom) {
			t.Fatalf("raw db error must pass through unchanged, got %v", execErr)
		}
		if errors.Is(execErr, tasks.ErrWorkerCrashed) {
			t.Fatalf("raw db error must not be wrapped as crash: %v", execErr)
		}
	})
}

// TestDomainErrConcurrentNotIdentityComparable Root-cause regression anchor: two independently
// constructed domain.ErrConcurrent() pointers are never equal (errors.Is is always false), so checks
// must use errors.As + Code. If Is/Unwrap is added to *domain.Error in the future, review this test
// and the check pattern in run.go together.
func TestDomainErrConcurrentNotIdentityComparable(t *testing.T) {
	if errors.Is(domain.ErrConcurrent(), domain.ErrConcurrent()) {
		t.Fatal("domain.ErrConcurrent constructs fresh pointers; errors.Is must not succeed by identity")
	}
	var de *domain.Error
	if !errors.As(domain.ErrConcurrent(), &de) || de.Code != domain.CodeConcurrent {
		t.Fatal("errors.As + Code must identify the concurrent domain error")
	}
}
