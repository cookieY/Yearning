// run_execute_contest_test.go Unit test for Execute contention translation: 1004 contention
// errors returned by claimAttempt/applyResult must be translated into tasks.ErrWorkerCrashed
// (crash semantics: task does not enter a terminal state and converges via reclaim after lease expiry).
// Root-cause guard — domain.ErrConcurrent() constructs a fresh *domain.Error pointer each time
// without Is/Unwrap, so errors.Is across two independently constructed pointers is always false,
// and contention detection must use errors.As + Code.
//
// Because go.mod freezes dependencies without sqlmock/sqlite, a minimal database/sql/driver fake
// driver reproduces the only two statements touched on this path: reading the execution_attempts
// row (Query) and the claim CAS update (Exec, with configurable RowsAffected=0 for claim contention).
